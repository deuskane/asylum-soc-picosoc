#!/bin/bash
#-----------------------------------------------------------------------------
# Title      : Synthesis check of PicoSoC_top with ghdl --synth (post_run hook)
# Project    : Asylum
#-----------------------------------------------------------------------------
# File       : ghdl_synth.sh
# Author     : mrosiere
#-----------------------------------------------------------------------------
# Description: post_run hook of the lint_ghdl_synth (OpenBlaze8) and
#              lint_ghdl_synth_wardrv (WardRV_fsm) targets (cwd = fusesoc
#              work_root, after the run step : the ghdl -m of edalize has
#              analyzed (-Wall) and elaborated the top in library asylum).
#              Argument : CPU_MODEL (default OpenBlaze8), it must match the
#              firmware ROMs (ROM_user / ROM_supervisor) generated by the
#              target (pbcc_gen for OpenBlaze8, rvcc_gen for WardRV_fsm).
#              Synthesizes the top for each configuration below. Writes
#              synth_<config>.vhd (netlist) and synth_<config>.log, prints
#              the warnings of each configuration, fails if a synthesis
#              fails or infers a latch.
#-----------------------------------------------------------------------------
# Copyright (c) 2026
#-----------------------------------------------------------------------------
# Revisions  :
# Date        Version  Author   Description
# 2026-10-20  1.0      mrosiere Created
#-----------------------------------------------------------------------------

TOP=PicoSoC_top
TOP_LIB="--work=asylum --workdir=./asylum"     # "" for a wrapper top in library work
GHDL_OPT="--std=08 -Wall -fsynopsys -frelaxed -P./asylum"
CPU_MODEL=${1:-OpenBlaze8}

# Generics of the configurations
SOC1="-gSUPERVISOR=false -gUSER_SAFETY=none -gUSER_FAULT_INJECTION=false -gDEBUG_ENABLE=false"
NG_MEDIUM="-gFSYS=25000000 -gFSYS_INT=12500000 -gUSER_NB_SWITCH=6 -gUSER_BAUD_RATE=9600
           -gUSER_UART_DEPTH_TX=4 -gUSER_UART_DEPTH_RX=4
           -gUSER_SPI_DEPTH_CMD=4 -gUSER_SPI_DEPTH_TX=4 -gUSER_SPI_DEPTH_RX=4"
SOC4="-gSUPERVISOR=true -gUSER_SAFETY=tmr -gUSER_FAULT_INJECTION=true -gDEBUG_ENABLE=false"

# name : generics (CPU_MODEL is added)
case $CPU_MODEL in
    OpenBlaze8)
        CONFIGS=(
            "default       : "
            "soc1          : $SOC1"
            "soc4_ng_medium: $SOC4 $NG_MEDIUM"
            "basys         : -gUSER_NB_LED0=4 -gUSER_NB_LED1=1 -gRESET_POLARITY=high"
        );;
    WardRV_fsm)
        CONFIGS=(
            "wardrv_soc1           : $SOC1"
            "wardrv_soc4_ng_medium : $SOC4 $NG_MEDIUM"
            "wardrv_soc1x4         : $SOC1 -gUSER_NB_CPU=4"
        );;
    *)
        echo "ghdl_synth.sh : unknown CPU_MODEL $CPU_MODEL"
        exit 1;;
esac

nb_fail=0
for config in "${CONFIGS[@]}"; do
    name=$(echo "${config%%:*}" | tr -d ' ')
    generics="-gCPU_MODEL=$CPU_MODEL ${config#*:}"

    # shellcheck disable=SC2086
    ghdl --synth $GHDL_OPT $TOP_LIB $generics $TOP > "synth_${name}.vhd" 2> "synth_${name}.log"
    rc=$?

    if [ $rc -ne 0 ]; then
        status="FAIL (ghdl rc=$rc)"
    elif grep -qi "latch" "synth_${name}.log"; then
        status="FAIL (latch)"
    else
        status="PASS"
    fi
    [ "$status" = "PASS" ] || nb_fail=$((nb_fail + 1))
    nb_warn=$(grep -ci "warning" "synth_${name}.log")

    printf "ghdl --synth %-22s : %s (%d warnings)\n" "$name" "$status" "$nb_warn"
    if [ "$status" != "PASS" ]; then
        sed 's/^/    /' "synth_${name}.log"
    elif [ "$nb_warn" -ne 0 ]; then
        grep -i "warning" "synth_${name}.log" | sed 's/^/    /'
    fi
done

if [ $nb_fail -ne 0 ]; then
    echo "lint_ghdl_synth : FAIL ($nb_fail / ${#CONFIGS[@]} configurations)"
    exit 1
fi
echo "lint_ghdl_synth : PASS (${#CONFIGS[@]} configurations)"
